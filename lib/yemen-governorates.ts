// تطبيع النص العربي لتسهيل البحث (توحيد الهمزات والتاء المربوطة والألف المقصورة وإزالة التشكيل)
export function normalizeArabic(input: string): string {
  return input
    .trim()
    .replace(/[\u064B-\u065F\u0670]/g, "") // إزالة التشكيل
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/ـ/g, "") // إزالة التطويل
    .replace(/\s+/g, " ")
    .toLowerCase()
}
